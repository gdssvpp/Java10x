package com.nogdev.exerciciosarraylistgpt;

public class ContagemDecrescente {
    public static void main(String[] args) {
        // Crie um programa que imprima os números de 10 até 1 no console.
        //Objetivo: praticar decremento (i--).

        for(int i = 10; i >= 1; i--){
            System.out.println(i);
        }
    }
}
